# Explain one test-set row: create perturbed copies (5,000 by default), get the model's
# predictions, weight them by closeness, fit a linear model, and report 6 features
def lime_explain(i, **kwargs):
    return lime_explainer.explain_instance(X_test.values[i], predict_fn, num_features=6, **kwargs)

# One LIME bar chart per applicant. label=1 means "explain P(approved)".
