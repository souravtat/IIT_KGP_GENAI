"""Green bars push toward *approved*, red bars toward *rejected*.

Numeric features appear as rules such as `Capital Gain <= 0.00` because LIME **discretizes** numeric features into quartile bins by default. This makes explanations readable, but as we'll see in Section 2.5 it also changes what the explanation means.

Things to check in the output:
- Anita's approval is driven mostly by a very large capital gain.
- Priya's reasons mostly point toward rejection, except `Capital Loss > 0`, which LIME counts in her favour. Keep this in mind for the SHAP section.
- Meera's reasons point in both directions, which is what a borderline case looks like.

For an interactive version of any explanation, run `display(HTML(exp.as_html()))`.
"""

exp = lime_explain(people["Meera (borderline)"])
# R^2 of LIME's linear model on the weighted copies: 1 = perfect fit, 0 = no fit at all
