"""---
## 2. LIME on tabular data

LIME (Local Interpretable Model-agnostic Explanations) explains one prediction at a time:
1. Generate many perturbed copies of the instance.
2. Get the black-box model's prediction for each copy.
3. Weight each copy by how close it is to the original.
4. Fit a weighted linear model to these predictions. Its coefficients are the explanation.

### 2.1 What a local surrogate looks like

A 2-D toy example: a neural network with a curved decision boundary, and the straight line LIME fits around one point.
"""

from sklearn.datasets import make_moons
from sklearn.neural_network import MLPClassifier

# Toy data with 2 features, shaped like two interleaving half-moons,
# and a small neural network as the black box
Xm, ym = make_moons(n_samples=600, noise=0.25, random_state=1)
toy = MLPClassifier(hidden_layer_sizes=(32, 32), max_iter=3000, random_state=0).fit(Xm, ym)

x0 = np.array([0.2, 0.35])                       # the point we want to explain (the star)
rng = np.random.default_rng(0)
Z = x0 + rng.normal(0, 0.5, size=(800, 2))        # step 1: 800 perturbed copies scattered around x0
pz = toy.predict_proba(Z)[:, 1]                   # step 2: black-box prediction for each copy
w = np.exp(-np.sum((Z - x0) ** 2, 1) / 0.3 ** 2)  # step 3: weight, close to 1 near x0 and close to 0 far away
lin = Ridge(alpha=0.01).fit(Z, pz, sample_weight=w)  # step 4: weighted linear model = the explanation

# Everything below is plotting.
# Black-box prediction on a fine grid of points, to colour the background
xx, yy = np.meshgrid(np.linspace(-1.5, 2.5, 300), np.linspace(-1.2, 1.7, 300))
grid = toy.predict_proba(np.c_[xx.ravel(), yy.ravel()])[:, 1].reshape(xx.shape)

fig, ax = plt.subplots(figsize=(10, 7))
ax.contourf(xx, yy, grid, levels=20, cmap="RdBu_r", alpha=0.45)    # background colour: black-box probability
ax.contour(xx, yy, grid, levels=[0.5], colors="k", linewidths=2)   # black curve: where the black box predicts 0.5
ax.scatter(Z[:, 0], Z[:, 1], s=4 + 120 * w, c=pz, cmap="RdBu_r", edgecolor="k", linewidth=0.3)  # copies; bigger = more weight
# Green line: where the local linear model predicts exactly 0.5,
# i.e. intercept + a*x + b*y = 0.5, solved for y
a, b = lin.coef_; c0 = lin.intercept_
xs = np.linspace(-1.0, 1.0, 50)                  # only draw the line around the star
ax.plot(xs, (0.5 - c0 - a * xs) / b, "g--", lw=3, label="LIME's local linear boundary")
ax.scatter(*x0, marker="*", s=600, c="gold", edgecolor="k", zorder=5, label="instance being explained")
ax.set_xlim(-1.5, 2.5); ax.set_ylim(-1.2, 1.7); ax.legend(loc="lower left")
ax.set_title("Black curve: the real model.  Green dashes: LIME's local approximation")
plt.show()
# The explanation: how much each feature pushes the prediction up or down near the star
print("Local coefficients (feature1, feature2):", np.round(lin.coef_, 3))

"""The green line matches the real boundary near the star and is wrong further away. The explanation is only valid locally. The amount of perturbation (`0.5`) and the kernel width (`0.3`) both affect where the line ends up.

### 2.2 The LIME library
"""

# Set up the explainer once. training_data is not used to train anything: LIME uses it to
# learn what typical values look like (quartile bins for numeric features, how common each
# category is), so that it can generate realistic perturbed copies.
